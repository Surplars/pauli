// Native HS vector. Frame layout is injected by trap.rs, never hand counted.
.section .text
.balign 4
.global pauli_native_vector
pauli_native_vector:
    addi sp, sp, -{size}
    sd zero, {x0}(sp)
    sd x1, {x1}(sp)
    sd x3, {x3}(sp)
    sd x4, {x4}(sp)
    sd x5, {x5}(sp)
    sd x6, {x6}(sp)
    sd x7, {x7}(sp)
    sd x8, {x8}(sp)
    sd x9, {x9}(sp)
    sd x10, {x10}(sp)
    sd x11, {x11}(sp)
    sd x12, {x12}(sp)
    sd x13, {x13}(sp)
    sd x14, {x14}(sp)
    sd x15, {x15}(sp)
    sd x16, {x16}(sp)
    sd x17, {x17}(sp)
    sd x18, {x18}(sp)
    sd x19, {x19}(sp)
    sd x20, {x20}(sp)
    sd x21, {x21}(sp)
    sd x22, {x22}(sp)
    sd x23, {x23}(sp)
    sd x24, {x24}(sp)
    sd x25, {x25}(sp)
    sd x26, {x26}(sp)
    sd x27, {x27}(sp)
    sd x28, {x28}(sp)
    sd x29, {x29}(sp)
    sd x30, {x30}(sp)
    sd x31, {x31}(sp)
    addi t0, sp, {size}
    sd t0, {x2}(sp)
    csrr t0, sepc
    sd t0, {pc}(sp)
    csrr t0, sstatus
    sd t0, {status}(sp)
    csrr t0, scause
    sd t0, {cause}(sp)
    csrr t0, stval
    sd t0, {value}(sp)
    mv a0, sp
    call pauli_native_trap
    ld t0, {pc}(sp)
    csrw sepc, t0
    ld t0, {status}(sp)
    csrw sstatus, t0
    ld x1, {x1}(sp)
    ld x3, {x3}(sp)
    ld x4, {x4}(sp)
    ld x5, {x5}(sp)
    ld x6, {x6}(sp)
    ld x7, {x7}(sp)
    ld x8, {x8}(sp)
    ld x9, {x9}(sp)
    ld x10, {x10}(sp)
    ld x11, {x11}(sp)
    ld x12, {x12}(sp)
    ld x13, {x13}(sp)
    ld x14, {x14}(sp)
    ld x15, {x15}(sp)
    ld x16, {x16}(sp)
    ld x17, {x17}(sp)
    ld x18, {x18}(sp)
    ld x19, {x19}(sp)
    ld x20, {x20}(sp)
    ld x21, {x21}(sp)
    ld x22, {x22}(sp)
    ld x23, {x23}(sp)
    ld x24, {x24}(sp)
    ld x25, {x25}(sp)
    ld x26, {x26}(sp)
    ld x27, {x27}(sp)
    ld x28, {x28}(sp)
    ld x29, {x29}(sp)
    ld x30, {x30}(sp)
    ld x31, {x31}(sp)
    ld sp, {x2}(sp)
    sret
