// SENVCFG has no VS bank: install the incoming value and save the outgoing
// value on every switch, including a short exit from a resident vCPU.
.macro swap_senvcfg incoming, outgoing
    ld t1, \incoming
    csrrw t1, senvcfg, t1
    sd t1, \outgoing
.endm
